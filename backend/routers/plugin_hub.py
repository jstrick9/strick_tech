def stats():
    """Headline numbers for the hub landing page."""
    items = _full_catalog()
    inst = [i for i in items if i['installed']]
    return {
        'ok': True,
        'total_packs': len(items),
        'installed_packs': len(inst),
        'available_skills': sum(i['skill_count'] for i in items),
        'installed_skills': sum(i['skill_count'] for i in inst),
        'categories': len({i['category'] for i in items}),
    }
