# ── Endpoints ──────────────────────────────────────────────────────────────────
@router.get('/catalog')
def catalog(q: str = '', category: str = '', installed: str = ''):
    """Every plugin from every source, normalised into one shape."""
    items = _full_catalog()

    if q:
        needle = q.lower()
        items = [
            i for i in items
            if needle in i['name'].lower()
            or needle in i['description'].lower()
            or any(needle in str(t).lower() for t in i['tags'])
        ]
    if category:
        items = [i for i in items if i['category'] == category]
    if installed == 'true':
        items = [i for i in items if i['installed']]
    elif installed == 'false':
        items = [i for i in items if not i['installed']]

    return {
        'ok': True,
        'items': items,
        'total': len(items),
        'categories': sorted({i['category'] for i in _full_catalog() if i['category']}),
    }


@router.get('/installed')
def installed_list():
    """One list of what the user has, regardless of which backend owns it."""
    items = [i for i in _full_catalog() if i['installed']]
    return {'ok': True, 'items': items, 'total': len(items)}


@router.get('/collections')
def collections():
    """Curated bundles, annotated with live install state."""
    cat = {i['id']: i for i in _full_catalog()}
    out = []
    for c in COLLECTIONS:
        packs = [cat[p] for p in c['packs'] if p in cat]
        out.append({
            **c,
            'packs': packs,
            'available': len(packs),
            'installed_count': sum(1 for p in packs if p['installed']),
            'skill_total': sum(p['skill_count'] for p in packs),
        })
    return {'ok': True, 'collections': out}


@router.get('/pack/{pack_id}')
def pack_detail(pack_id: str):
    """Full detail INCLUDING the actual skills and their prompt templates.

    "What does this actually do before I install it" was unanswerable: the
    /api/plugins registry endpoint explicitly strips skills (`'skills': None`),
    so the only way to find out was to install the pack and go look in the
    Skills pane.
    """
    entry = next((i for i in _full_catalog() if i['id'] == pack_id), None)
    if not entry:
        return JSONResponse({'ok': False, 'error': 'Plugin not found'}, status_code=404)

    skills: list[dict] = []
    if entry['source'] == SOURCE_PLUGINS:
        from .plugins import BUILTIN_REGISTRY

        raw = next((p for p in BUILTIN_REGISTRY if p['id'] == pack_id), None)
        skills = (raw or {}).get('skills') or []
    else:
        from .marketplace import get_pack

        detail = get_pack(pack_id)
        if isinstance(detail, dict):
            skills = detail.get('skills') or []

    return {
        'ok': True,
        **entry,
        'skills': [
            {
                'id': s.get('id'),
                'name': s.get('name'),
                'emoji': s.get('emoji', '⚡'),
                'description': s.get('description', ''),
                'inputs': s.get('inputs', []),
                'prompt_template': s.get('prompt_template', ''),
            }
            for s in skills
            if isinstance(s, dict)
        ],
        'skill_count': len(skills),
    }


@router.post('/install/{pack_id}')
async def install(pack_id: str, req: Request):
    """Install from whichever backend owns the pack. One button, either source."""
    entry = next((i for i in _full_catalog() if i['id'] == pack_id), None)
    if not entry:
        return JSONResponse({'ok': False, 'error': 'Plugin not found'}, status_code=404)
    if entry['installed']:
        return JSONResponse(
            {'ok': False, 'error': f"{entry['name']} is already installed", 'installed': True},
            status_code=409,
        )

    if entry['source'] == SOURCE_PLUGINS:
        from .plugins import install_plugin

        result = await install_plugin(pack_id, req)
    else:
        from .marketplace import install_pack

        result = await install_pack(pack_id, req)

    if isinstance(result, JSONResponse):
        return result
    if not isinstance(result, dict) or not result.get('ok'):
        return JSONResponse(
            {'ok': False, 'error': (result or {}).get('error', 'Install failed')}, status_code=400
        )

    added = result.get('skills_added', result.get('skills', 0))
    return {
        'ok': True,
        'id': pack_id,
        'name': entry['name'],
        'source': entry['source'],
        'skills_added': added,
        'message': f"Installed {entry['name']} — {added} skill(s) ready in Skills",
    }


@router.post('/uninstall/{pack_id}')
def uninstall(pack_id: str):
    """Uninstall, routing to the owning backend."""
    entry = next((i for i in _full_catalog() if i['id'] == pack_id), None)
    if not entry:
        return JSONResponse({'ok': False, 'error': 'Plugin not found'}, status_code=404)
    if not entry['installed']:
        return JSONResponse(
            {'ok': False, 'error': f"{entry['name']} is not installed"}, status_code=409
        )

    if entry['source'] == SOURCE_PLUGINS:
        from .plugins import uninstall_plugin

        result = uninstall_plugin(pack_id)
    else:
        from .marketplace import uninstall_pack

        result = uninstall_pack(pack_id)

    if isinstance(result, JSONResponse):
        return result
    return {'ok': True, 'id': pack_id, 'name': entry['name'], 'detail': result}


@router.post('/collections/{collection_id}/install')
async def install_collection(collection_id: str, req: Request):
    """Install every pack in a starter collection in one action."""
    coll = next((c for c in COLLECTIONS if c['id'] == collection_id), None)
    if not coll:
        return JSONResponse({'ok': False, 'error': 'Collection not found'}, status_code=404)

    results, added_total, failed = [], 0, []
    for pid in coll['packs']:
        entry = next((i for i in _full_catalog() if i['id'] == pid), None)
        if not entry:
            continue
        if entry['installed']:
            results.append({'id': pid, 'status': 'already_installed'})
            continue
        r = await install(pid, req)
        if isinstance(r, JSONResponse):
            failed.append(pid)
            results.append({'id': pid, 'status': 'failed'})
        else:
            added_total += r.get('skills_added', 0) or 0
            results.append({'id': pid, 'status': 'installed', 'skills': r.get('skills_added', 0)})

    return {
        'ok': not failed,
        'collection': coll['name'],
        'results': results,
        'skills_added': added_total,
        'failed': failed,
        'message': f"{coll['name']}: {added_total} skill(s) added",
    }


@router.get('/updates')
def updates():
    """Packs with a newer version than the one installed.

    mkt_releases and /marketplace/installed/check-updates already existed but
    nothing surfaced them, so an installed pack could go stale indefinitely.
    """
    out: list[dict] = []
    try:
        from .marketplace import check_updates

        for u in (check_updates() or {}).get('updates', []):
            out.append({
                'id': u.get('pack_id'), 'name': u.get('name'),
                'icon': u.get('icon') or '📦',
                'installed_version': u.get('installed_ver'),
                'latest_version': u.get('latest_ver'), 'source': SOURCE_MARKET,
            })
    except Exception as e:  # pragma: no cover
        log.warning('hub: update check failed: %s', e)

    try:
        from .plugins import BUILTIN_REGISTRY, _load_installed

        for pid, rec in _load_installed().items():
            pack = next((p for p in BUILTIN_REGISTRY if p.get('id') == pid), None)
            if not pack:
                continue
            latest = pack.get('version') or '1.0.0'
            if rec.get('version') and rec['version'] != latest:
                out.append({
                    'id': pid, 'name': pack.get('name', pid),
                    'icon': pack.get('emoji') or '🧩',
                    'installed_version': rec.get('version'),
                    'latest_version': latest, 'source': SOURCE_PLUGINS,
                })
    except Exception as e:  # pragma: no cover
        log.warning('hub: plugin update check failed: %s', e)

    seen, uniq = set(), []
    for u in out:
        if u['id'] in seen:
            continue
        seen.add(u['id'])
        uniq.append(u)
    return {'ok': True, 'updates': uniq, 'count': len(uniq)}


@router.get('/provenance/{pack_id}')
def provenance(pack_id: str):
    """Where an installed pack came from, and its content hash.

    Custom plugins arrive from an arbitrary URL or a paste and were previously
    indistinguishable from curated content once installed.
    """
    from .plugins import _load_installed

    rec = _load_installed().get(pack_id)
    if not rec:
        return JSONResponse({'ok': False, 'error': 'Not installed'}, status_code=404)
    return {
        'ok': True, 'id': pack_id,
        'origin': rec.get('origin', 'unknown'),
        'origin_url': rec.get('origin_url', ''),
        'content_hash': rec.get('content_hash', ''),
        'installed_at': rec.get('installed_at', ''),
        'warnings': rec.get('warnings', []),
        'trusted': rec.get('origin') == 'builtin',
    }


@router.post('/review')
async def review_before_install(req: Request):
    """Static safety review of a pack WITHOUT installing it."""
    try:
        body = await req.json()
    except Exception:
        body = {}
    pack = body.get('plugin_json') or body.get('pack') or body
    if not isinstance(pack, dict):
        return JSONResponse({'ok': False, 'error': 'Expected a plugin object'}, status_code=400)

    from ..services.plugin_safety import review_pack

    return {'ok': True, **review_pack(pack)}


