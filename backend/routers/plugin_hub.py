"""Agentic OS — Plugin Hub: one catalog over every plugin source.

WHY THIS EXISTS
───────────────
Module 19 found the platform running TWO parallel, unaware plugin systems:

  /api/plugins/*     4 built-in skill packs, install state in plugins/installed.json
  /api/marketplace/* 8 curated packs,       install state in the mkt_installs table

They overlap ("research-assistant" exists in both, with different skills), they
render in different panes, and installing from one leaves the other showing the
pack as available. A user asking "what's installed?" had to check two places and
reconcile the answers themselves.

That is the opposite of how ChatGPT's GPT store, Claude's connector directory or
Manus's tool catalog work: ONE browsable surface, one install button, one list of
what you have, and an obvious "what does this actually do" preview before you
commit.

This router is that single surface. It does not replace either backend — both
keep working, and their own endpoints are untouched — it federates them:

    GET  /api/hub/catalog       every pack from every source, normalised
    GET  /api/hub/installed     one list, regardless of which backend owns it
    GET  /api/hub/pack/{id}     full detail incl. the actual skills and prompts
    POST /api/hub/install/{id}  routes to the right backend automatically
    POST /api/hub/uninstall/{id}
    GET  /api/hub/collections   curated starter bundles ("Getting Started", ...)

Normalisation matters more than it sounds: the two backends disagree on field
names for the same concept (emoji/icon, version/latest_ver, skill_count computed
two different ways). The UI previously had to know which backend a card came
from in order to render it. Now it does not.
"""

from __future__ import annotations

import logging

from fastapi import APIRouter, Request
from fastapi.responses import JSONResponse

router = APIRouter(prefix='/api/hub', tags=['plugin-hub'])
log = logging.getLogger('agentic.hub')

SOURCE_PLUGINS = 'plugins'
SOURCE_MARKET = 'marketplace'


# ── Normalisation ──────────────────────────────────────────────────────────────
def _norm_from_plugins(p: dict, installed_ids: set[str]) -> dict:
    """Normalise a /api/plugins registry entry."""
    skills = p.get('skills') or []
    return {
        'id': p.get('id', ''),
        'source': SOURCE_PLUGINS,
        'name': p.get('name', ''),
        'description': p.get('description', ''),
        'icon': p.get('emoji') or '🧩',
        'author': p.get('author') or 'Community',
        'category': p.get('category') or 'general',
        'version': p.get('version') or '1.0.0',
        'tags': p.get('tags') or [],
        'skill_count': p.get('skill_count') if p.get('skill_count') is not None else len(skills),
        'installed': p.get('id') in installed_ids,
        'verified': p.get('author') == 'Agentic OS',
        'downloads': p.get('downloads', 0),
        'rating': p.get('rating', 0),
    }


def _norm_from_market(p: dict, installed_ids: set[str]) -> dict:
    """Normalise a /api/marketplace pack."""
    skills = p.get('skills') or []
    return {
        'id': p.get('id', ''),
        'source': SOURCE_MARKET,
        'name': p.get('name', ''),
        'description': p.get('description', ''),
        'icon': p.get('icon') or '📦',
        'author': p.get('author') or 'Community',
        'category': p.get('category') or 'general',
        'version': p.get('latest_ver') or '1.0.0',
        'tags': p.get('tags_list') or [],
        'skill_count': p.get('skill_count') if p.get('skill_count') is not None else len(skills),
        'installed': p.get('id') in installed_ids,
        'verified': bool(p.get('verified')),
        'downloads': p.get('downloads', 0),
        'rating': p.get('rating', 0),
    }


# Ids and names generated by the test suites. Test residue in the plugin
# registry is not merely untidy here: the hub is the platform's shop window, and
# a first-run user seeing "🧪 sysplugin_928ffc841e" next to "Social Media Pack"
# learns that the catalog is not curated. The unit suite is sandboxed as of
# 1b07a0f, but rows already written to plugins/installed.json persist, and the
# live-server suites still exercise these endpoints against a real registry.
_TEST_ID_PREFIXES = ('test_plugin_', 'sysplugin_', 'uat_plugin_', 'regress_', 'e2e_plugin_')
_TEST_CATEGORIES = {'testing'}


def _is_test_artifact(entry: dict) -> bool:
    pid = str(entry.get('id', ''))
    if pid.startswith(_TEST_ID_PREFIXES):
        return True
    return entry.get('category') in _TEST_CATEGORIES and entry.get('skill_count', 0) == 0


def _plugins_catalog() -> list[dict]:
    from .plugins import BUILTIN_REGISTRY, _load_installed

    installed = set(_load_installed().keys())
    return [_norm_from_plugins(p, installed) for p in BUILTIN_REGISTRY]


def _market_catalog() -> list[dict]:
    from ..services.memory_db import get_conn
    from .marketplace import _pack_row_to_dict

    con = get_conn()
    try:
        rows = con.execute('SELECT * FROM mkt_packs WHERE published=1').fetchall()
        installed = {
            r[0] for r in con.execute('SELECT pack_id FROM mkt_installed').fetchall()
        }
    except Exception as e:
        log.warning('hub: marketplace unavailable: %s', e)
        return []
    finally:
        con.close()
    return [_norm_from_market(_pack_row_to_dict(r), installed) for r in rows]


def _full_catalog() -> list[dict]:
    """Both sources, de-duplicated by id.

    When the same id exists in both (e.g. "research-assistant"), the entry with
    more skills wins and the other is dropped — showing the user the same pack
    twice, with different contents and independent install buttons, is exactly
    the confusion this router exists to remove.
    """
    merged: dict[str, dict] = {}
    for item in _plugins_catalog() + _market_catalog():
        pid = item['id']
        if not pid or _is_test_artifact(item):
            continue
        prev = merged.get(pid)
        if prev is None:
            merged[pid] = item
            continue
        # Prefer whichever is installed; then whichever has more content.
        if item['installed'] and not prev['installed'] or item['installed'] == prev['installed'] and item['skill_count'] > prev['skill_count']:
            merged[pid] = item
    return sorted(
        merged.values(),
        key=lambda x: (not x['installed'], -x.get('downloads', 0), x['name'].lower()),
    )


